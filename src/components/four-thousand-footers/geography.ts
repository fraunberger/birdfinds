function widen(line: ReadonlyArray<readonly [number, number, number]>): LatLon[] {
    const east = line.map(([lat, lon, half]) => [lat, lon + half] as const);
    const west = line.map(([lat, lon, half]) => [lat, lon - half] as const).reverse();
    return [...east, ...west];
}

